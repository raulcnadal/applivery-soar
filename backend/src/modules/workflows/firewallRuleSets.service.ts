/**
 * Firewall Rule Sets (Windows network-remediation, Zero Networks-style) —
 * port of main.py:5025-5486. RESTORE MODEL is deliberately NOT a full
 * firewall snapshot/restore: every rule is tagged with a Group unique to its
 * rule set (firewallGroupTag), layered ON TOP of whatever's already on the
 * device. "Restore" just deletes every rule in that Group — whatever was
 * already there underneath is automatically back in effect. DELIVERY reuses
 * the existing 'runScript' MDM action verbatim (see mdmActionExecutor.ts's
 * applyFirewallRuleSet/restoreFirewallRuleSet branches).
 */

export const FIREWALL_GROUP_PREFIX = "BPSOAR-FW";

export function firewallGroupTag(ruleSetId: string): string {
  return `${FIREWALL_GROUP_PREFIX}-${ruleSetId}`;
}

/** Escapes a value for safe interpolation inside a PowerShell double-quoted string. Port of `_ps_escape` (main.py:5086). */
function psEscape(s: string | null | undefined): string {
  return (s || "").replace(/`/g, "``").replace(/"/g, '`"');
}

export interface FirewallRulePayload {
  id?: string | null;
  name?: string;
  direction?: string; // 'inbound' | 'outbound'
  action?: string; // 'block' | 'allow'
  protocol?: string; // 'TCP' | 'UDP' | 'Any'
  localPorts?: string;
  remoteAddresses?: string;
  profile?: string;
  enabled?: boolean;
}

/** One New-NetFirewallRule invocation. Port of `_firewall_rule_to_powershell` (main.py:5093-5122). */
function firewallRuleToPowershell(rule: FirewallRulePayload, groupTag: string, idx: number): string {
  const direction = (rule.direction || "inbound").toLowerCase() === "inbound" ? "Inbound" : "Outbound";
  const action = (rule.action || "block").toLowerCase() === "block" ? "Block" : "Allow";
  const displayName = `${groupTag}-${idx}-${(rule.name || "rule").slice(0, 60)}`;
  const parts = [
    `New-NetFirewallRule -DisplayName "${psEscape(displayName)}"`,
    `-Group "${groupTag}"`,
    `-Direction ${direction}`,
    `-Action ${action}`,
    `-Enabled ${rule.enabled !== false ? "True" : "False"}`,
  ];
  const protocol = (rule.protocol || "Any").trim();
  if (protocol.toLowerCase() !== "any") {
    parts.push(`-Protocol ${protocol}`);
    const localPorts = (rule.localPorts || "").trim();
    if (localPorts && localPorts.toLowerCase() !== "any") parts.push(`-LocalPort ${localPorts}`);
  }
  const remote = (rule.remoteAddresses || "").trim();
  if (remote && remote.toLowerCase() !== "any") parts.push(`-RemoteAddress "${psEscape(remote)}"`);
  const profile = (rule.profile || "Any").trim();
  if (profile.toLowerCase() !== "any") parts.push(`-Profile ${profile}`);
  return `${parts.join(" ")} | Out-Null`;
}

const WINDOWS_FIREWALL_OS_DEFAULT_INBOUND = "Block";
const WINDOWS_FIREWALL_OS_DEFAULT_OUTBOUND = "Allow";

export interface FirewallRuleSetLike {
  id: string;
  name: string;
  ensureFirewallEnabled: boolean;
  defaultInboundAction: string;
  defaultOutboundAction: string;
  rules: FirewallRulePayload[];
}

/** Port of `_generate_firewall_apply_script` (main.py:5127-5191). */
export function generateFirewallApplyScript(ruleSet: FirewallRuleSetLike): string {
  const group = firewallGroupTag(ruleSet.id);
  const name = ruleSet.name || "Firewall Rule Set";
  const rules = ruleSet.rules || [];
  const lines: string[] = [
    `# Auto-generated by Applivery SOAR — Firewall Rule Set "${psEscape(name)}"`,
    `# Rule set id: ${ruleSet.id}`,
    "# Do not edit on-device — make changes in Workflows > Firewall Policies and re-apply.",
    '$ErrorActionPreference = "Stop"',
    `$Group = "${group}"`,
    "",
    "# Idempotent: clear any rules we previously created under this group before recreating",
    "# them, so re-applying (rule set edited, workflow re-run) never leaves duplicates or",
    "# stale rules behind.",
    "Get-NetFirewallRule -Group $Group -ErrorAction SilentlyContinue | Remove-NetFirewallRule -ErrorAction SilentlyContinue",
    "",
  ];

  const profileCmd = ["Set-NetFirewallProfile", "-All"];
  if (ruleSet.ensureFirewallEnabled) profileCmd.push("-Enabled True");
  const defaultIn = ruleSet.defaultInboundAction || "notConfigured";
  const defaultOut = ruleSet.defaultOutboundAction || "notConfigured";
  if (defaultIn !== "notConfigured") profileCmd.push(`-DefaultInboundAction ${defaultIn[0].toUpperCase()}${defaultIn.slice(1)}`);
  if (defaultOut !== "notConfigured") profileCmd.push(`-DefaultOutboundAction ${defaultOut[0].toUpperCase()}${defaultOut.slice(1)}`);
  if (profileCmd.length > 2) {
    if (ruleSet.ensureFirewallEnabled) {
      lines.push(
        "# No EDR present (per this rule set's own configuration) — verify Windows Firewall",
        "# itself is enabled, otherwise nothing below would actually be enforced.",
      );
    } else {
      lines.push(
        "# EDR present (per this rule set's own configuration) — Windows Firewall's enabled",
        "# state is left exactly as-is; only the default posture below (if configured) changes.",
      );
    }
    if (defaultIn !== "notConfigured" || defaultOut !== "notConfigured") {
      lines.push(
        '# Changing the profile\'s DEFAULT action (not a rule) is what makes a genuine "allow',
        "# only these exceptions\" posture possible: Windows Firewall always lets an explicit",
        "# Block rule beat an explicit Allow rule regardless of which was created when or by",
        '# whom, so a "block everything, then allow X" pair of RULES would never actually let',
        "# X through. Flipping the profile default instead means unmatched traffic is blocked/",
        "# allowed by default, and this rule set's own Allow/Block rules below are what carve",
        "# out the exceptions — which behave normally against a changed default.",
      );
    }
    lines.push(profileCmd.join(" "), "");
  }

  if (rules.length) {
    lines.push(
      "# Block rules always take precedence over Allow rules in Windows Firewall",
      "# regardless of creation order — containment (Block) rules below are reliable",
      "# even alongside pre-existing/EDR-managed rules; a narrow Allow rule is only",
      "# guaranteed to hold if nothing else is blocking that same traffic first.",
    );
  }
  rules.forEach((rule, idx) => lines.push(firewallRuleToPowershell(rule, group, idx)));
  lines.push("", `Write-Output "Applied firewall rule set '${psEscape(name)}' (${rules.length} rule(s), group=$Group)."`);
  return lines.join("\n");
}

/** Port of `_generate_firewall_restore_script` (main.py:5193-5224). */
export function generateFirewallRestoreScript(ruleSet: FirewallRuleSetLike): string {
  const group = firewallGroupTag(ruleSet.id);
  const name = ruleSet.name || "Firewall Rule Set";
  const lines: string[] = [
    `# Auto-generated by Applivery SOAR — restores a device from Firewall Rule Set "${psEscape(name)}"`,
    `# Removes every rule this rule set created (group=${group}). Whatever firewall state`,
    "# pre-existed underneath is automatically back in effect once these are gone — no",
    "# snapshot was ever taken or is needed.",
    '$ErrorActionPreference = "Stop"',
    `$Group = "${group}"`,
    "Get-NetFirewallRule -Group $Group -ErrorAction SilentlyContinue | Remove-NetFirewallRule -ErrorAction SilentlyContinue",
  ];
  const defaultIn = ruleSet.defaultInboundAction || "notConfigured";
  const defaultOut = ruleSet.defaultOutboundAction || "notConfigured";
  if (defaultIn !== "notConfigured" || defaultOut !== "notConfigured") {
    const restoreCmd = ["Set-NetFirewallProfile", "-All"];
    if (defaultIn !== "notConfigured") restoreCmd.push(`-DefaultInboundAction ${WINDOWS_FIREWALL_OS_DEFAULT_INBOUND}`);
    if (defaultOut !== "notConfigured") restoreCmd.push(`-DefaultOutboundAction ${WINDOWS_FIREWALL_OS_DEFAULT_OUTBOUND}`);
    lines.push("# Revert the profile default posture this rule set changed, back to Windows' own OS default.", restoreCmd.join(" "));
  }
  lines.push(`Write-Output "Restored device from firewall rule set '${psEscape(name)}' (removed group=$Group)."`);
  return lines.join("\n");
}

/**
 * Generates fresh Apply/Restore PowerShell, uploads each as a new Applivery
 * script Asset, and creates (first save) or updates in place (later saves)
 * the two Action Library entries pointing at them. Port of
 * `_provision_firewall_ruleset_library_entries` (main.py:5259-5314).
 */
async function provisionFirewallRulesetLibraryEntries(
  authorization: string,
  orgBase: string,
  workspaceSlug: string,
  ruleSet: FirewallRuleSetLike,
  existingApplyId: string | null | undefined,
  existingRestoreId: string | null | undefined,
): Promise<{ applyId: string | null; restoreId: string | null; error: string | null }> {
  const applyScript = generateFirewallApplyScript(ruleSet);
  const restoreScript = generateFirewallRestoreScript(ruleSet);
  const uploadBase = orgBase.replace("https://api.applivery.io", "https://upload.applivery.io");
  const name = ruleSet.name || "Firewall Rule Set";
  const managedNote = "Auto-generated and managed by the Firewall Policy Library — edit the rule set there, not this entry.";

  const applyResult = await createScriptAsset(authorization, uploadBase, `${name} — Apply (Firewall)`, managedNote, applyScript, "windows", null, true);
  if (applyResult.error || !applyResult.asset) return { applyId: null, restoreId: null, error: `Could not upload the Apply script to Applivery: ${applyResult.error}` };
  const restoreResult = await createScriptAsset(authorization, uploadBase, `${name} — Restore (Firewall)`, managedNote, restoreScript, "windows", null, true);
  if (restoreResult.error || !restoreResult.asset) return { applyId: null, restoreId: null, error: `Could not upload the Restore script to Applivery: ${restoreResult.error}` };

  async function upsert(existingId: string | null | undefined, asset: { id: string; name?: string }, label: string): Promise<string> {
    if (existingId) {
      const entry = await prisma.actionLibraryEntry.findFirst({ where: { workspaceSlug, id: existingId } });
      if (entry) {
        await prisma.actionLibraryEntry.update({ where: { id: entry.id }, data: { assetId: asset.id, assetName: asset.name } });
        return entry.id;
      }
    }
    const created = await prisma.actionLibraryEntry.create({
      data: {
        workspaceSlug, type: "script", name: `${name} — ${label} (Firewall)`, description: managedNote,
        platform: "windows", assetId: asset.id, assetName: asset.name, arguments: "", scope: "machine",
      },
    });
    return created.id;
  }

  const applyId = await upsert(existingApplyId, applyResult.asset, "Apply");
  const restoreId = await upsert(existingRestoreId, restoreResult.asset, "Restore");
  return { applyId, restoreId, error: null };
}

