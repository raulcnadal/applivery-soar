export async function listFirewallRuleSets(workspaceSlug: string) {
  return prisma.firewallRuleSet.findMany({ where: { workspaceSlug }, orderBy: { createdAt: "asc" } });
}

export interface FirewallRuleSetPayload {
  name: string;
  description?: string | null;
  ensureFirewallEnabled?: boolean;
  defaultInboundAction?: string;
  defaultOutboundAction?: string;
  rules: FirewallRulePayload[];
}

export async function createFirewallRuleSet(authorization: string, workspaceSlug: string, payload: FirewallRuleSetPayload, actorEmail: string) {
  const id = crypto.randomUUID();
  const rules = (payload.rules ?? []).map((r) => ({ ...r, id: r.id || crypto.randomUUID() }));
  const headers = { Authorization: authorization };
  const orgBase = await resolveOrgBase(headers, workspaceSlug);

  const draft: FirewallRuleSetLike = {
    id, name: payload.name, ensureFirewallEnabled: payload.ensureFirewallEnabled ?? true,
    defaultInboundAction: payload.defaultInboundAction ?? "notConfigured", defaultOutboundAction: payload.defaultOutboundAction ?? "notConfigured",
    rules,
  };
  const { applyId, restoreId, error } = await provisionFirewallRulesetLibraryEntries(authorization, orgBase, workspaceSlug, draft, null, null);
  if (error) throw new HttpError(502, error);

  const created = await prisma.firewallRuleSet.create({
    data: {
      id, workspaceSlug, name: payload.name, description: payload.description ?? "",
      ensureFirewallEnabled: draft.ensureFirewallEnabled, defaultInboundAction: draft.defaultInboundAction, defaultOutboundAction: draft.defaultOutboundAction,
      rules: rules as any, applyLibraryId: applyId, restoreLibraryId: restoreId,
    },
  });
  await recordAuditEvent(workspaceSlug, {
    category: "workflow", action: "firewall_ruleset_created", actor: actorEmail,
    targetType: "firewall_ruleset", targetId: created.id, targetName: created.name,
    message: `Firewall Rule Set "${created.name}" created (${rules.length} rule(s), ${draft.ensureFirewallEnabled ? "no EDR — will ensure firewall enabled" : "EDR present — firewall state left alone"})`,
  });
  return created;
}

export async function updateFirewallRuleSet(authorization: string, workspaceSlug: string, ruleSetId: string, payload: FirewallRuleSetPayload, actorEmail: string) {
  const existing = await prisma.firewallRuleSet.findFirst({ where: { workspaceSlug, id: ruleSetId } });
  if (!existing) throw new HttpError(404, "Firewall Rule Set not found");

  const rules = (payload.rules ?? []).map((r) => ({ ...r, id: r.id || crypto.randomUUID() }));
  const headers = { Authorization: authorization };
  const orgBase = await resolveOrgBase(headers, workspaceSlug);

  const draft: FirewallRuleSetLike = {
    id: ruleSetId, name: payload.name, ensureFirewallEnabled: payload.ensureFirewallEnabled ?? true,
    defaultInboundAction: payload.defaultInboundAction ?? "notConfigured", defaultOutboundAction: payload.defaultOutboundAction ?? "notConfigured",
    rules,
  };
  const { applyId, restoreId, error } = await provisionFirewallRulesetLibraryEntries(authorization, orgBase, workspaceSlug, draft, existing.applyLibraryId, existing.restoreLibraryId);
  if (error) throw new HttpError(502, error);

  const updated = await prisma.firewallRuleSet.update({
    where: { id: ruleSetId },
    data: {
      name: payload.name, description: payload.description ?? "",
      ensureFirewallEnabled: draft.ensureFirewallEnabled, defaultInboundAction: draft.defaultInboundAction, defaultOutboundAction: draft.defaultOutboundAction,
      rules: rules as any, applyLibraryId: applyId, restoreLibraryId: restoreId,
    },
  });
  await recordAuditEvent(workspaceSlug, {
    category: "workflow", action: "firewall_ruleset_updated", actor: actorEmail,
    targetType: "firewall_ruleset", targetId: ruleSetId, targetName: updated.name,
    message: `Firewall Rule Set "${updated.name}" updated (${rules.length} rule(s)) — on-device scripts regenerated, already-applied devices need the workflow action re-run to pick up the change`,
  });
  return updated;
}

export async function deleteFirewallRuleSet(workspaceSlug: string, ruleSetId: string, actorEmail: string) {
  const existing = await prisma.firewallRuleSet.findFirst({ where: { workspaceSlug, id: ruleSetId } });
  if (!existing) throw new HttpError(404, "Firewall Rule Set not found");
  await prisma.firewallRuleSet.delete({ where: { id: ruleSetId } });
  await recordAuditEvent(workspaceSlug, {
    category: "workflow", action: "firewall_ruleset_deleted", actor: actorEmail,
    targetType: "firewall_ruleset", targetId: ruleSetId, targetName: existing.name,
    message: `Firewall Rule Set "${existing.name}" deleted from the library. Devices it was already applied to keep those rules until explicitly restored.`,
  });
  return { status: "deleted" };
}
